/**
 * Finding the code, and refusing to guess.
 *
 * Two failure modes, and they are not symmetric. Missing a code costs Alex a
 * trip to his mail. Relaying the WRONG one — an order number, a year, the other
 * code in a two-code mail — gets a wrong value autofilled somewhere that
 * matters. So every ambiguous case here asserts null.
 */
import { codeIn, codeFor, stripHtml, saysCode, looksLikeWord } from './code.mjs';

let pass = 0, fail = 0;
const check = (what, ok, detail) => {
  if (ok) { pass++; console.log(`  ok   ${what}`); }
  else { fail++; console.log(`  FAIL ${what}${detail ? ` -> ${detail}` : ''}`); }
};

console.log('Real mail Alex actually received');
{
  // ForeFlight, 2026-09-01. Alphanumeric, alone on a line, with "5 minutes"
  // and an address in the surrounding text. An all-digit extractor found
  // nothing here, which is why this file exists.
  const foreflight = `Your ForeFlight Verification Code
Hi, Alex
Your verification code is below
This code and link will expire in 5 minutes.
Enter your verification code.
A6BX6M
If you did not request this code, please contact us at team@foreflight.com.
Thank you for your support and your business.
— Team ForeFlight
Purchase or Renew Support Latest News
ForeFlight, LLC

ForeFlight
team@foreflight.com`;
  check('the ForeFlight alphanumeric code is found', codeIn(foreflight) === 'A6BX6M',
        codeIn(foreflight));

  // Google, same evening. The code is alone on a line, the label is two lines
  // above it, and "2-step" sits in the text — a leading-zero code, which a
  // numeric parse would have mangled to 15151.
  const google = `Hello
Here's your 2-step verification code
Use the verification code to authenticate
015151`;
  check('a leading-zero code survives as a string', codeIn(google) === '015151',
        codeIn(google));

  // PayPal, same evening. Labelled inline, with "10 minutes" in the same
  // sentence — two digits, so not a candidate, which is why 4 is the floor.
  const paypal = `Here's your code

Your verification code is 449827 and will expire in 10 minutes. For your `
    + `security, don't share it with anyone. PayPal will never call to ask you for this info.`;
  check('the PayPal code is taken and the "10 minutes" is not',
        codeIn(paypal) === '449827', codeIn(paypal));

  // Zoom. The hard one: the mail carries a full sign-in audit trail, and
  // "08/08/2026" puts a four-digit year in the text. The code is saved by being
  // alone on its line while the year is not.
  const zoom = `Hi Alex Rivera,
We detected an unusual sign-in from a device or location you don't usually use. If this was you, enter the code below to sign in to Zoom.
464188
The code will expire in 10 minutes.
Please review the sign in activity details below:
Date	08/08/2026 01:05:27 PM
Browser	Safari
Operating System	macOS
Location	the state(US)
If this wasn't you, please let us know here. We recommend that you update your password and enable two-step verification to secure your account.
Thank you,
The Zoom Team`;
  check('Zoom: the code wins over the 2026 in the timestamp',
        codeIn(zoom) === '464188', codeIn(zoom));

  // Code above the greeting rather than below it — the label line ends with a
  // colon and the code is two lines down.
  const oneTime = `Your one-time access code is:

832258

Hello ,

 

Please enter the above one-time access code in the appropriate field. Your code expires in 10 mins.`;
  check('a code above the greeting is found', codeIn(oneTime) === '832258', codeIn(oneTime));

  // A five-digit code with a full date on the very next line. "2026" is a
  // four-digit candidate and loses only because it is not alone on its line.
  const dated = `The security code to verify your account is:

32848
Friday, July 17, 2026 at 10:23:52 AM
If this wasn't you
This code was generated by an attempt to create an account with this email, \
if you did not request it or you think it was a mistake, please contact our support team`;
  check('a five-digit code beats the year on the following line',
        codeIn(dated) === '32848', codeIn(dated));

  const intuit = `Verify your Intuit account

Verification code:

339739


You requested a verification code. You can use this code to complete the process.

Thanks,
Intuit Team`;
  check('Intuit: label, blank line, code', codeIn(intuit) === '339739', codeIn(intuit));

  // The hardest real sample so far. The signature block carries a street
  // number (7901), a ZIP (33702) and a phone number (5552000009) — the first
  // two are code-shaped. The code survives because it alone sits on its own
  // line; every decoy is embedded in an address line.
  const agent = `Hi, Alex Rivera,
Use the verification code below to complete your action for State Registered Agent LLC
996014

This code will expire in 15 minutes. If you didn't request this code, you can safely ignore this email.
Alex Sutton

	500 Pine Rd, STE 300
Springfield, ST 00002

	5552000009

	www.co8f41.example
agent@co8f41.example`;
  check('a footer full of numbers does not beat the code',
        codeIn(agent) === '996014', codeIn(agent));
}

console.log('\nThe ordinary shapes');
{
  check('labelled on one line',
        codeIn('Your verification code is 284913') === '284913');
  check('with a colon', codeIn('Verification code: 739201') === '739201');
  check('alone on a line under a sentence',
        codeIn('Enter this to continue\n\n447201\n\nIt expires shortly') === '447201');
  check('Swedish', codeIn('Din engångskod är 483920') === '483920');
  check('the only number in the whole mail',
        codeIn('Someone signed in. Use 6612 to confirm it was you.') === '6612');
  check('an 8-digit code', codeIn('Your access code is 48392011') === '48392011');
}

console.log('\nWhat is not a code');
{
  check('no candidate at all', codeIn('Someone signed in from a new device') === null);
  check('empty', codeIn('') === null);
  check('null', codeIn(null) === null);
  check('a 3-digit number is too short', codeIn('Your code is 123') === null);
  check('a 9-digit number is too long — that is an order id',
        codeIn('Order 123456789 has shipped') === null);
  // Words must not become codes — but ForeFlight has issued Alex both
  // A6BX6M and HEJKRR, so letters-only tokens cannot simply be rejected.
  check('a stop-listed word is not a code', codeIn('\nSUPPORT\n') === null);
  check('  ...nor a short one', codeIn('\nTEAM\n') === null);
  check('a letters-only code alone on a line IS taken',
        codeIn('Enter your verification code:\nHEJKRR\n') === 'HEJKRR');

  // Position alone is not enough: a token must also not look like a word.
  // An earlier version read IOTA alone on a line as a code, on the theory that
  // position vouched for it. It does not vouch for enough.
  check('a word-shaped acronym alone on a line is NOT a code',
        codeIn('\nIOTA\n') === null, codeIn('\nIOTA\n'));
  check('  ...but gibberish alone on a line is',
        codeIn('\nHEJKRR\n') === 'HEJKRR');

  // Loose in a body, with nothing vouching for it, a word is still a word.
  check('a letters-only token floating in prose is NOT a code',
        codeIn('Please contact SUPPORT about this') === null);
  check('  ...even an unknown one', codeIn('Filed under IOTA last week') === null);
}

console.log('\nWhen the message says outright that it contains a code');
{
  // Alex's suggestion: an explicit phrase is stronger evidence than any
  // shape rule, so it unlocks the looser token test — but only for strings
  // that do not look like words.
  check('gibberish loose in a body IS a code once the mail says so',
        codeIn('Your verification code follows. HEJKRR expires soon.') === 'HEJKRR',
        codeIn('Your verification code follows. HEJKRR expires soon.'));
  check('  ...and without the phrase it is not',
        codeIn('The reference HEJKRR expires soon.') === null);
  check('a stop-listed word never becomes a code, phrase or not',
        codeIn('Your verification code: contact SUPPORT') === null);
  check('a word-shaped acronym stays refused even with the phrase',
        codeIn('Your verification code was filed under IOTA somewhere') === null,
        codeIn('Your verification code was filed under IOTA somewhere'));

  check('gibberish detection: HEJKRR is not a word', !looksLikeWord('HEJKRR'));
  check('  ...SUPPORT is', looksLikeWord('SUPPORT'));
  check('  ...WELCOME is', looksLikeWord('WELCOME'));
  check('  ...and a vowel-heavy acronym reads as word-like, which is the safe way',
        looksLikeWord('IOTA'));

  check('the phrase itself is recognised', saysCode('Your verification code'));
  check('  ...in Swedish too', saysCode('Din engångskod'));
  check('  ...and ordinary mail does not trip it', !saysCode('Your order has shipped'));
}

console.log('\nAmbiguity is null, never a guess');
{
  check('two different labelled numbers',
        codeIn('Code 123456 or code 654321') === null);
  check('two different candidates alone on lines',
        codeIn('\n123456\n\n654321\n') === null);
  check('two candidates loose in the text',
        codeIn('Ref 4471 relates to invoice 8890') === null);
  // The same value twice is not ambiguity — templates repeat the code.
  check('the SAME value twice is still an answer',
        codeIn('Your code is 284913. Enter 284913 to continue.') === '284913');
}

console.log('\nA label cannot reach across lines');
{
  // The dangerous shape: "your code" on one line, an unrelated number three
  // lines down. Rule 1 must not connect them.
  const t = 'Your verification code\nis on its way\nOrder 998877 shipped today';
  check('a label does not claim a number on another line', codeIn(t) === '998877',
        `${codeIn(t)} — rule 3 may still take it as the only candidate`);

  const two = 'Your verification code\nis on its way\nOrder 998877\nInvoice 112233';
  check('  ...and with two such numbers the answer is null', codeIn(two) === null);
}

console.log('\nHTML');
{
  check('tags are stripped',
        codeIn(stripHtml('<p>Your code is <b>284913</b></p>')) === '284913');
  // Tags become spaces, so two runs split across elements cannot fuse into a
  // number that was never displayed. `3456` is then the only candidate and rule
  // 3 takes it, which is correct — the point is that `123456` never appears.
  check('adjacent tags do not fuse two numbers into one',
        codeIn(stripHtml('<span>12</span><span>3456</span>')) !== '123456',
        codeIn(stripHtml('<span>12</span><span>3456</span>')));
  check('script contents are dropped whole',
        codeIn(stripHtml('<script>var x=99887766;</script><p>Code: 284913</p>')) === '284913');
  check('style contents are dropped whole',
        codeIn(stripHtml('<style>.a{width:12345px}</style><p>Code: 284913</p>')) === '284913');
  check('entities decode', stripHtml('a&amp;b').includes('a&b'));
}

console.log('\nSubject first, body only when needed');
{
  let fetched = 0;
  const body = async () => { fetched++; return { text: 'Your code is 111222' }; };

  let r = await codeFor('Your verification code is 284913', body);
  check('a code in the subject is used', r.code === '284913' && r.from === 'subject');
  check('  ...and no body is fetched at all', fetched === 0,
        'a body request that never had to happen is one more thing that can fail');

  r = await codeFor('Your verification code', body);
  check('otherwise the body is read', r.code === '111222' && r.from === 'body');
  check('  ...exactly once', fetched === 1);

  r = await codeFor('Your verification code', async () => { throw new Error('429'); });
  check('a body that cannot be fetched is not fatal',
        r.code === null && r.from === 'body-unavailable');

  r = await codeFor('Your verification code', async () => ({ html: '<b>A6BX6M</b>' }));
  check('html bodies work when there is no plain text part', r.code === 'A6BX6M', r.code);

  r = await codeFor('Your verification code');
  check('no fetcher at all is not fatal', r.code === null && r.from === 'none');
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
